if DB_AUTH_MODE == "windows":
    DATABASE_CONFIG[
        "Trusted_Connection"
    ] = "yes"

    DATABASE_CONFIG["OPTIONS"][
        "extra_params"
    ] = (
        "TrustServerCertificate="
        f"{DB_TRUST_SERVER_CERTIFICATE};"
    )

elif DB_AUTH_MODE == "sql":
    if not DB_USER or not DB_PASSWORD:
        raise RuntimeError(
            "DB_USER y DB_PASSWORD son "
            "obligatorios cuando "
            "DB_AUTH_MODE=sql."
        )

    DATABASE_CONFIG["USER"] = DB_USER
    DATABASE_CONFIG[
        "PASSWORD"
    ] = DB_PASSWORD

    DATABASE_CONFIG[
        "Trusted_Connection"
    ] = "no"

    DATABASE_CONFIG["OPTIONS"][
        "extra_params"
    ] = (
        "Encrypt=yes;"
        "TrustServerCertificate="
        f"{DB_TRUST_SERVER_CERTIFICATE};"
        "MultiSubnetFailover=Yes;"
    )

elif DB_AUTH_MODE == "managed_identity":
    DATABASE_CONFIG["OPTIONS"][
        "extra_params"
    ] = (
        "Authentication="
        "ActiveDirectoryMsi;"
        "Encrypt=yes;"
        "TrustServerCertificate=no;"
        "MultiSubnetFailover=Yes;"
    )

else:
    raise RuntimeError(
        "DB_AUTH_MODE debe ser uno de: "
        "windows, sql o managed_identity."
    )

